  assert.match(s, /\?view=buy/)
  assert.match(s, /data-pw-like-count/)
  assert.match(s, /data-pw-stat="likes"/)
  assert.match(s, /hideBrokenPdpImgs/)
  assert.match(s, /data-pw-pdp-img-broken/)
  assert.match(s, /_\\d\+x\\d\+\(\?:q\\d\+\)\?/)
