  assert.match(s, /function paintHelpfulBtn/)
  assert.match(s, /pw-pdp-rq-sample-box/)
  assert.match(s, /function rqToast/)
  assert.match(s, /function paintNeedBuy/)
  assert.match(s, /canReviewLive/)
  assert.match(s, /highlight=/)
  assert.match(s, /reviewsPurchaseRequired/)
  assert.match(s, /qaSeeList/)
