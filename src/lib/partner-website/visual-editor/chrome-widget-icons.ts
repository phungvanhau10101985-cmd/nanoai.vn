const CHROME_GLYPH_SET = new Set<string>(CHROME_GLYPH_IDS)

export function isChromeGlyphId(value: unknown): value is ChromeGlyphId {
  return typeof value === 'string' && CHROME_GLYPH_SET.has(value)
}

export function canPickChromeGlyph(kind?: ChromeGlyphKind | null): boolean {
  if (!kind) return false
  return Boolean(KIND_GLYPHS[kind]?.length)
}

export function chromeGlyphsForKind(kind?: ChromeGlyphKind | null): readonly ChromeGlyphId[] {
  if (!kind) return []
  return KIND_GLYPHS[kind] || []
}

export function defaultChromeGlyph(kind?: string | null): ChromeGlyphId | '' {
  return chromeGlyphsForKind(kind)[0] || ''
}

export function normalizeChromeGlyph(kind: string | null | undefined, raw: unknown): ChromeGlyphId | '' {
  const list = chromeGlyphsForKind(kind)
  if (!list.length) return ''
  if (typeof raw === 'string' && list.includes(raw as ChromeGlyphId)) return raw as ChromeGlyphId
  return list[0]
}

