import assert from 'node:assert/strict'
import test from 'node:test'
import { emptyImeSession, imeCandidates, imeCommitCandidate, imeFeed, imeFlush, imeTypeText, primeKanaLexicon, primePinyinLexicon } from './engine'

test('chinese pinyin picks a word and a character', async () => {
  await primePinyinLexicon()
  const typed = imeFeed('zh', emptyImeSession(), 'nihao')
  assert.equal(imeCandidates('zh', typed.session)[0], '你好')
  assert.equal(imeTypeText('zh', 'nihao'), '你好')
  assert.equal(imeTypeText('zh', 'zhongguo'), '中国')
  assert.equal(imeTypeText('zh', 'dengjikou'), '登机口')
  const flushed = imeFlush('zh', imeFeed('zh', emptyImeSession(), 'ni').session)
  assert.equal(flushed.commit, '你')
})

test('chinese sentence segments like the google pinyin bar', async () => {
  await primePinyinLexicon()
  const typed = imeFeed('zh', emptyImeSession(), 'jintianzuoshenme')
  const candidates = imeCandidates('zh', typed.session)
  assert.deepEqual(candidates.slice(0, 5), ['今天做什么', '今天', '金田', '进', '金'])
  assert.equal(imeTypeText('zh', 'jintianzuoshenme'), '今天做什么')
  const picked = imeCommitCandidate('zh', typed.session, 1)
  assert.equal(picked.commit, '今天')
  assert.equal(picked.session.raw, 'zuoshenme')
  assert.equal(imeCandidates('zh', picked.session)[0], '做什么')
  const partial = imeFeed('zh', emptyImeSession(), 'jintianzuoshe')
  assert.equal(imeCandidates('zh', partial.session)[0], '今天做什么')
  assert.equal(imeTypeText('zh', 'buzhidao'), '不知道')
  assert.equal(imeTypeText('zh', 'women'), '我们')
  assert.equal(imeTypeText('zh', 'xiexie'), '谢谢')
  assert.equal(imeTypeText('zh', "xi'an"), '西安')
})

test('japanese romaji converts like a desktop ime', async () => {
  await primeKanaLexicon()
  assert.equal(imeTypeText('ja', 'konnichiwa'), 'こんにちは')
  assert.equal(imeTypeText('ja', 'katta'), '買った')
  assert.equal(imeTypeText('ja', 'chotto'), 'ちょっと')
  assert.equal(imeTypeText('ja', 'kyu'), 'きゅ')
  assert.equal(imeTypeText('ja', 'nihongo'), '日本語')
  assert.equal(imeTypeText('ja', 'gakkou'), '学校')
  assert.equal(imeTypeText('ja', 'watashi'), '私')
  const typed = imeFeed('ja', emptyImeSession(), 'katta')
  assert.equal(imeCandidates('ja', typed.session)[0], '買った')
  assert.equal(imeFeed('ja', typed.session, ' ').commit, '買った')
})

