// Builds the simplified-Chinese lexicon from Android PinyinIME's Apache-2.0 dictionary.
// Usage: node src/app/hoc-tieng-anh-ai/ime/build-pinyin-lexicon.mjs <rawdict_utf16_65105_freq.txt>
import fs from 'node:fs'

const source = process.argv[2]
if (!source) {
  console.error('Pass the UTF-16 rawdict_utf16_65105_freq.txt path')
  process.exit(1)
}

const text = fs.readFileSync(source).toString('utf16le').replace(/^\uFEFF+/g, '')
const byPy = new Map()
const syllables = new Set()

for (const line of text.split(/\r?\n/)) {
  const parts = line.trim().split(/\s+/)
  if (parts.length < 4 || parts[2] !== '0') continue
  const word = parts[0]
  const freq = Math.round(Number(parts[1]))
  const tokens = parts.slice(3)
  if (!word || !Number.isFinite(freq) || freq <= 0) continue
  if (/[\s`\\$]/.test(word)) continue
  const py = tokens.join('')
  if (!/^[a-z]+$/.test(py)) continue
  for (const token of tokens) syllables.add(token)
  const list = byPy.get(py)
  if (list) list.push([word, freq])
  else byPy.set(py, [[word, freq]])
}

const lines = []
for (const py of [...byPy.keys()].sort()) {
  const words = byPy.get(py).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'zh'))
  lines.push([py, ...words.flatMap(([word, freq]) => [word, String(freq)])].join(' '))
}

const pack = lines.join('\n')
if (pack.includes('`') || pack.includes('${') || pack.includes('\\')) {
  throw new Error('Lexicon contains characters that cannot sit in a template string')
}

const out = `// Generated by build-pinyin-lexicon.mjs. Do not edit by hand.
// Simplified-Chinese entries from Android PinyinIME rawdict_utf16_65105_freq.txt
// Copyright 2009 The Android Open Source Project
// Licensed under the Apache License, Version 2.0
// http://www.apache.org/licenses/LICENSE-2.0
export const PINYIN_LEXICON_PACK = \`
${pack}
\`
export const PINYIN_SYLLABLES: readonly string[] = ${JSON.stringify([...syllables].sort())}
`

const target = new URL('./pinyin-lexicon-data.ts', import.meta.url)
fs.writeFileSync(target, out)
console.log(`words ${lines.length} syllables ${syllables.size} bytes ${Buffer.byteLength(out)}`)
